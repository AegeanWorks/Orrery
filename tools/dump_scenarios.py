"""Dump the nine built-in scenarios as JSON for the sealed browser build.

The live studio must reproduce the Python engine exactly, so it does not
re-implement the scenario constructors: this script resolves every parametric
initial condition (perihelion starts, rotations, barycentre centering) through
the real :mod:`orrery.scenarios` code and writes full-precision floats.

Run from the project root:

    python tools/dump_scenarios.py           # writes data/scenarios.js
    python tools/dump_scenarios.py --check   # fail when the file is stale
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from orrery.scenarios import scenario_keys, get_scenario  # noqa: E402

OUTPUT = PROJECT_ROOT / "data" / "scenarios.js"


def _float(value: float) -> str:
    """A round-trippable JSON/JS number literal for a finite float."""
    if value == 0.0:
        return "0.0" if math.copysign(1.0, value) > 0 else "-0.0"
    return repr(value)


def scenario_payload(scenario) -> dict:
    bodies = []
    for body in scenario.bodies:
        bodies.append({
            "name": body.name,
            "mass": _float(body.mass),
            "x": _float(body.pos.x),
            "y": _float(body.pos.y),
            "vx": _float(body.vel.x),
            "vy": _float(body.vel.y),
            "symbol": body.symbol,
            "color": body.color,
            "charge": _float(body.charge),
        })
    return {
        "key": scenario.key,
        "title": scenario.title,
        "description": scenario.description,
        "g": _float(scenario.g),
        "dt": _float(scenario.dt),
        "span": _float(scenario.span),
        "extent": [_float(scenario.extent[0]), _float(scenario.extent[1])],
        "steps_per_frame": scenario.steps_per_frame,
        "trail_length": scenario.trail_length,
        "record_every": scenario.record_every,
        "default_frames": scenario.default_frames,
        "time_unit": scenario.time_unit,
        "distance_unit": scenario.distance_unit,
        "mass_unit": scenario.mass_unit,
        "speed_unit": scenario.speed_unit,
        "speed_scale": _float(scenario.speed_scale),
        "c": None if scenario.c is None else _float(scenario.c),
        "k_e": _float(scenario.k_e),
        "bodies": bodies,
    }


def build_document() -> dict:
    return {
        "schema": 1,
        "generator": "python tools/dump_scenarios.py -- do not edit",
        "scenarios": [scenario_payload(get_scenario(key)) for key in scenario_keys()],
    }


def render() -> str:
    document = build_document()
    # A sealed live build may not fetch anything, so the data ships as a script
    # that assigns one global; the core reads it through its loader.
    header = ("// AUTO-GENERATED by `python tools/dump_scenarios.py` -- do not edit.\n"
              "// Initial conditions are resolved by the real Python scenario code\n"
              "// so the browser build replays the engine's own numbers.\n"
              "globalThis.ORRERY_SCENARIOS = ")
    return header + json.dumps(document, indent=1, ensure_ascii=False) + ";\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="fail when data/dump is stale")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.is_file():
            print(f"missing: {OUTPUT}")
            return 1
        if OUTPUT.read_text(encoding="utf-8") != expected:
            print("stale: run python tools/dump_scenarios.py, then commit the result.")
            return 1
        print(f"OK: {OUTPUT} matches the current scenarios.")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT} ({len(build_document()['scenarios'])} scenarios)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
